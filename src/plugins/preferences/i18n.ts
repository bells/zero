const dictionaries = {
  "zh-CN": zh,
  "en-US": en,
} as const;

export type TranslationKey = keyof typeof zh;

export function resolveLanguage(
  preference: LanguagePreference,
  systemLanguage: string,
): ResolvedLanguage {
  if (preference === "zh-CN" || preference === "en-US") {
    return preference;
  }

  return systemLanguage.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

export function createTranslator(language: ResolvedLanguage) {
  return (key: TranslationKey) => dictionaries[language][key];
}
