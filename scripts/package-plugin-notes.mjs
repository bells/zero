import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { build } from 'vite';
import JSZip from 'jszip';
import { validateWebManifest } from './lib/plugin-protocol.mjs';
const root=path.resolve('examples/plugin-notes');
const out=path.resolve('build/plugin-notes');
const development=process.argv.includes('--development');
await build({configFile:false,publicDir:false,build:{outDir:out,emptyOutDir:true,lib:{entry:path.join(root,'notes.ts'),formats:['es'],fileName:()=> 'notes.js'},target:'es2020',minify:true}});
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
if(development) manifest.engines.zero='>=0.1.0 <0.2.0';
const issues=validateWebManifest(manifest);if(issues.length) throw new Error(JSON.stringify(issues));
for(const file of ['index.html','notes.css']) fs.copyFileSync(path.join(root,file),path.join(out,file));
fs.writeFileSync(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
const zip=new JSZip();
for(const file of ['index.html','notes.css','notes.js','manifest.json']) zip.file(file,fs.readFileSync(path.join(out,file)),{date:new Date('2026-01-01T00:00:00Z')});
const bytes=await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE',compressionOptions:{level:9}});
const output=path.resolve(`build/plugin-notes${development?'-development':''}.zplugin`);fs.writeFileSync(output,bytes);
console.log(JSON.stringify({output,sha256:createHash('sha256').update(bytes).digest('hex'),development,releaseApproved:false}));
